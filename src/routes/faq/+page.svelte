		<h2>Who can register?</h2>
		<p>
			Registration is open to any current leaseholders and tenants of Waterloo Gardens.
		</p>

		<h2>Why is my account pending?</h2>
		<p>
			All new accounts must be approved by a director before you gain full access. This keeps the
			portal private to residents. Approval is usually granted within a few days — you'll receive
			an email when your account is approved or if there's an issue.
		</p>

		<h2>What can I do without logging in?</h2>
		<p>
			You can read the <a href="/channels/announcements">Announcements</a> board and browse this
			page and <a href="/about">About</a>. To post in the Residents' Forum or access the Document
			Library you need to <a href="/register">register</a> and be approved.
		</p>

		<h2>I have a building issue — who do I contact?</h2>
		<p>
			For repairs, cleaning, communal areas, and any other day-to-day operational matters, please
			contact <strong>LBM</strong> (our managing agent) or speak to the <strong>porter</strong>
			directly. Issues raised through them are properly logged and acted on more quickly than
			going to directors.
		</p>
