		<h2>Our building</h2>
		<p>
			Waterloo Gardens is a residential building in Islington, London. This portal is
			the residents' central hub for announcements from the management company, shared documents,
			and communication between neighbours.
		</p>

		<h2>What is a leaseholder?</h2>
		<p>
			Most flats at Waterloo Gardens are sold on long leases. As a
			<strong>leaseholder</strong>, you own the right to occupy your flat for the duration of your
			lease. You pay a service charge to cover the upkeep of the building's common parts,
			insurance, and management costs.
		</p>
		<p>
			Leaseholders have legal rights under the Landlord and Tenant Acts and the Commonhold and
			Leasehold Reform Act 2002, including the right to be consulted on major works and the right
			to form a residents' association.
		</p>

		<h2>What is the freehold?</h2>
		<p>
			The <strong>freehold</strong> is absolute ownership of the land and the building itself.
			Historically, the freehold of many residential blocks was held by landlord companies with
			no connection to the people who lived there. The freeholder ultimately owns the building
			once all leases expire.
		</p>

		<h2>Right to Manage</h2>
		<p>
			Under the Commonhold and Leasehold Reform Act 2002, leaseholders in qualifying buildings
			can take over the management of their building from the freeholder — without having to buy
			the freehold. This is known as exercising the <strong>Right to Manage</strong> (RTM).
		</p>
		<p>
			The residents of Waterloo Gardens exercised their Right to Manage and formed an RTM company
			to take responsibility for the day-to-day running of the building. This includes arranging
			maintenance, managing the service charge, and ensuring the building meets its legal
			obligations.
		</p>

		<h2>The directors</h2>
		<p>
			The RTM company is run by a board of <strong>directors</strong> elected from among the
			leaseholders. Directors are unpaid volunteers who give their time to manage the building on
			behalf of all residents. They are responsible for appointing contractors, setting the
			service charge budget, and keeping residents informed.
		</p>
		<p>
			If you have a general question or concern, you can post in the <a href="/channels/general">Residents' Forum</a>.
			<strong>For urgent matters, please contact <a href="/faq#current-directors" class="highlight-link">the directors</a> directly using the details on the FAQ page.</strong>
</p>
